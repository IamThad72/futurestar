  "church-outline": churchOutlineUrl,
  "church-filled": churchFilledUrl,
};

const props = defineProps({
  name: { type: String, required: true },
  size: { type: [Number, String], default: 24 },
  filled: { type: Boolean, default: false },
  /**
   * Accepted and ignored. Ionicons weight is set by the artwork
   * (outline vs filled), not by a stroke width. Kept so callers
   * that still pass strokeWidth do not break.
   */
  strokeWidth: { type: [Number, String], default: undefined },
});

const resolved = computed(() => resolveIcon(props.name, props.filled));

watch(
  () => props.name,
  (name) => {
    if (!name || resolveIcon(name, false).known || !import.meta.dev) return;
    console.warn(`[AppIcon] Unknown icon "${name}". Rendering help-circle-outline.`);
  },
  { immediate: true },
);

const iconBind = computed(() => {
  const spec = resolved.value;
  if (spec.customId) {
    const src = CUSTOM_URLS[spec.customId];
    return src ? { src } : { icon: ION_ICONS.helpCircleOutline };
  }
  if (!spec.exportName) return null;
  return { icon: ION_ICONS[spec.exportName] || ION_ICONS.helpCircleOutline };
});

const iconStyle = computed(() => {
  const raw = props.size;
  const css = typeof raw === "number" || /^\d+(\.\d+)?$/.test(String(raw)) ? `${raw}px` : String(raw);
  return {
    width: css,
    height: css,
    fontSize: css,
    flexShrink: 0,
  };
});
